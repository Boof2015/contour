# Build an installer payload from an explicit allowlist. Never package the whole
# build/repository directory: it contains private data and development tools.
[CmdletBinding()]
param([Parameter(Mandatory=$true)][string]$BinaryDirectory,
      [Parameter(Mandatory=$true)][string]$OutputDirectory,
      [Parameter(Mandatory=$true)][ValidatePattern('^\d+\.\d+\.\d+(-[A-Za-z0-9.-]+)?$')][string]$Version,
      [ValidateSet('Release','RelWithDebInfo')][string]$Configuration='Release')
. (Join-Path $PSScriptRoot 'ReleasePayload.ps1')
$source=[IO.Path]::GetFullPath($BinaryDirectory)
$destination=[IO.Path]::GetFullPath($OutputDirectory).TrimEnd('\')
if ($destination -eq [IO.Path]::GetPathRoot($destination) -or
    $destination.StartsWith($source+'\',[StringComparison]::OrdinalIgnoreCase) -or
    $source.StartsWith($destination+'\',[StringComparison]::OrdinalIgnoreCase) -or $source -ieq $destination) {
    throw 'Release output must be separate from the build input.'
}
Assert-ReleasePath $source
$parent=Split-Path $destination -Parent
# Check existing ancestors before creating anything: even a missing parent may
# sit below a junction that redirects writes elsewhere.
$ancestor=$parent
while (-not (Test-Path -LiteralPath $ancestor)) {
    $next=Split-Path $ancestor -Parent
    if (-not $next -or $next -eq $ancestor) { throw 'Cannot resolve the release output parent.' }
    $ancestor=$next
}
Assert-ReleasePath $ancestor
[void][IO.Directory]::CreateDirectory($parent);Assert-ReleasePath $parent
if (Test-Path -LiteralPath $destination) { $null=Test-ReleasePayload $destination }
$id=[guid]::NewGuid().ToString('D')
$temporary=Join-Path $parent ('.contour-stage-'+$id)
$previous=Join-Path $parent ('.contour-previous-'+$id)
[void][IO.Directory]::CreateDirectory($temporary)
try {
    $records=@(foreach ($relative in @(Get-ReleaseFiles)) {
        $inputFile=Join-Path $source $relative
        if (-not (Test-Path -LiteralPath $inputFile -PathType Leaf)) { throw ('Missing release file: '+$relative+'. Build the contour target first.') }
        Assert-ReleasePath $inputFile
        if ([IO.Path]::GetExtension($relative) -in @('.exe','.dll')) { Assert-ReleaseBinary $inputFile }
        $outputFile=Join-Path $temporary $relative
        [void][IO.Directory]::CreateDirectory((Split-Path $outputFile -Parent))
        Copy-Item -LiteralPath $inputFile -Destination $outputFile
        $inputHash=(Get-FileHash -LiteralPath $inputFile -Algorithm SHA256).Hash
        $outputHash=(Get-FileHash -LiteralPath $outputFile -Algorithm SHA256).Hash
        if ($inputHash -cne $outputHash) { throw 'Build files changed while staging. Finish the build and retry.' }
        [pscustomobject]@{path=$relative;sha256=$outputHash;bytes=(Get-Item -LiteralPath $outputFile).Length}
    })
    $manifest=[ordered]@{schema=1;kind='ContourReleasePayload';version=$Version;architecture='x64';configuration=$Configuration;
        minimumWindowsBuild=22000;prerequisites=@('Microsoft Visual C++ v14 Redistributable (x64)','Microsoft Edge WebView2 Evergreen Runtime');
        files=$records}
    [IO.File]::WriteAllText((Join-Path $temporary 'release.json'),($manifest | ConvertTo-Json -Depth 6),[Text.UTF8Encoding]::new($false))
    $null=Test-ReleasePayload $temporary
    # Replace only an unchanged payload generated by this tool. Every resolved
    # move/delete target is a direct child of the requested output's parent.
    if (Test-Path -LiteralPath $destination) {
        $null=Test-ReleasePayload $destination
        Move-Item -LiteralPath $destination -Destination $previous
    }
    try { Move-Item -LiteralPath $temporary -Destination $destination }
    catch {
        if (Test-Path -LiteralPath $previous) { Move-Item -LiteralPath $previous -Destination $destination }
        throw
    }
    if (Test-Path -LiteralPath $previous) {
        $null=Test-ReleasePayload $previous
        if ((Get-Item -LiteralPath $previous).Parent.FullName -cne $parent) { throw 'Unexpected staging cleanup path.' }
        Remove-Item -LiteralPath $previous -Recurse -Force
    }
    Write-Output ('Release payload: '+$destination)
    Write-Output ($records.Count.ToString()+' shipping files; hashes and x64 binaries verified.')
} finally {
    if (Test-Path -LiteralPath $temporary) {
        if ((Get-Item -LiteralPath $temporary).Parent.FullName -cne $parent) { throw 'Unexpected temporary staging path.' }
        Assert-ReleasePath $temporary
        foreach ($item in Get-ChildItem -LiteralPath $temporary -Recurse -Force) { Assert-ReleasePath $item.FullName }
        Remove-Item -LiteralPath $temporary -Recurse -Force
    }
}
